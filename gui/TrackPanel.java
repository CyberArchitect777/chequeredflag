    public void paintComponent( Graphics g )
    {
        Graphics2D g2d = (Graphics2D) g;
        Dimension d = getSize();

        // fill background
        Color oldColor = g2d.getColor();
        g2d.setColor(getBackground());
        g2d.fillRect(0, 0, d.width, d.height );
        g2d.setColor(oldColor);

        // On first drawing, adjust zooming and panning
        if ( m_fFirstTime )
        {
            m_fFirstTime = false;

            // set zooming and panning values so that track
            // appears in the middle of the window.
            Rectangle r = m_track.getBoundingRectangle();

            // Choose zoom factor so that a border of at least 10 percent
            // remains on each side of the track.
            double dScaleX = d.getWidth() / (r.getWidth() * 1.2);
            double dScaleY = d.getHeight() / (r.getHeight() * 1.2);
            if ( dScaleX > dScaleY )
                m_scale = dScaleY;
            else
                m_scale = dScaleX;

            // Center track in window
            standardTrans.setToIdentity();
            // Negative Y scale effectively changes Y direction (ascending
            // values from botton to top)
            standardTrans.scale( 1.0, -1.0 );
            standardTrans.translate( (d.getWidth() / 2.0) - m_scale * r.getCenterX(),
                                     -(d.getHeight() / 2.0) - m_scale * r.getCenterY() );
        }

        // change drawing direction to have positive y values going up.
        // Also panning could be done by the transformation, but not zooming
        // because automatic zoom looks bad.
        AffineTransform oldTrans = g2d.getTransform();
        g2d.transform( standardTrans );

        // draw all track segments
        TrackSegments trackSegments = m_track.getTrackSegments();
        TrackSegment trackSegment;
        m_fLeftFenceBridgedPrev = false;
        m_fRightFenceBridgedPrev = false;
        // Array for storing coordinates for display of "bridged" fence.
        // index 0: starting point of left bridged fence
        // index 1: end point of left bridged fence (up to current segment)
        // index 2/3: similar for right bridged fence.
        m_aXBridgePoints = new int[ 4 ];
        m_aYBridgePoints = new int[ 4 ];
        // Get initial fence distance from track header
        m_nLeftFenceDistPrev = m_track.getTrackDataHeader().getFenceDistL();
        m_nRightFenceDistPrev = m_track.getTrackDataHeader().getFenceDistL();

        for ( int i = 1; i <= trackSegments.size(); i++ )
        {
            trackSegment = trackSegments.getAt( i );

            if ( trackSegment.getCurvature() == 0 )
            {
                // Straight
                // Draw track segment itself.
                int aXPoints[] = new int[ 4 ];
                int aYPoints[] = new int[ 4 ];
                // Width unit is 1/1024 of TLU.
                double dXDiff = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
                double dYDiff = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
                aXPoints[ 0 ] = new Double((trackSegment.getPosXStart() - dXDiff) * m_scale).intValue();
                aYPoints[ 0 ] = new Double((trackSegment.getPosYStart() + dYDiff) * m_scale).intValue();
                aXPoints[ 1 ] = new Double((trackSegment.getPosXStart() + dXDiff) * m_scale).intValue();
                aYPoints[ 1 ] = new Double((trackSegment.getPosYStart() - dYDiff) * m_scale).intValue();

                dXDiff = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;
                dYDiff = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;
                aXPoints[ 2 ] = new Double((trackSegment.getPosXEnd() + dXDiff) * m_scale).intValue();
                aYPoints[ 2 ] = new Double((trackSegment.getPosYEnd() - dYDiff) * m_scale).intValue();
                aXPoints[ 3 ] = new Double((trackSegment.getPosXEnd() - dXDiff) * m_scale).intValue();
                aYPoints[ 3 ] = new Double((trackSegment.getPosYEnd() + dYDiff) * m_scale).intValue();
                g2d.drawPolygon( aXPoints, aYPoints, 4 );
            } // Straight
            else
            {
                // Curve
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    // outer line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                    // inner line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                }
                else
                {
                    // left turn: give start/end angle in opposite order
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                    // inner line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                }
            } // curve

            // Paint kerbs
            paintKerbs(trackSegment, g2d);

            // Paint fence
            paintFence(trackSegment, g2d);
        }

        // draw all pit lane segments
        // reset fence data.
        m_fLeftFenceBridgedPrev = false;
        m_fRightFenceBridgedPrev = false;
        // Pit lane uses same fence distance as track???
        m_nLeftFenceDistPrev = m_track.getTrackDataHeader().getFenceDistL();
        m_nRightFenceDistPrev = m_track.getTrackDataHeader().getFenceDistL();

        oldColor = g2d.getColor();
        g2d.setColor(Color.blue);
        trackSegments = m_track.getPitlaneSegments();
        for ( int i = 1; i <= trackSegments.size(); i++ )
        {
            trackSegment = trackSegments.getAt( i );

            if ( trackSegment.getCurvature() == 0 )
            {
                // Straight
                int aXPoints[] = new int[ 4 ];
                int aYPoints[] = new int[ 4 ];
                // Width unit is 1/1024 of TLU.
                double dXDiff = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
                double dYDiff = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
                aXPoints[ 0 ] = new Double((trackSegment.getPosXStart() - dXDiff) * m_scale).intValue();
                aYPoints[ 0 ] = new Double((trackSegment.getPosYStart() + dYDiff) * m_scale).intValue();
                aXPoints[ 1 ] = new Double((trackSegment.getPosXStart() + dXDiff) * m_scale).intValue();
                aYPoints[ 1 ] = new Double((trackSegment.getPosYStart() - dYDiff) * m_scale).intValue();

                dXDiff = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;
                dYDiff = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;
                aXPoints[ 2 ] = new Double((trackSegment.getPosXEnd() + dXDiff) * m_scale).intValue();
                aYPoints[ 2 ] = new Double((trackSegment.getPosYEnd() - dYDiff) * m_scale).intValue();
                aXPoints[ 3 ] = new Double((trackSegment.getPosXEnd() - dXDiff) * m_scale).intValue();
                aYPoints[ 3 ] = new Double((trackSegment.getPosYEnd() + dYDiff) * m_scale).intValue();
                g2d.drawPolygon( aXPoints, aYPoints, 4 );
            }
            else
            {
                // Curve
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    // outer line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                    // inner line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                }
                else
                {
                    // left turn: give start/end angle in opposite order
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() + ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                    // inner line
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthStart()) / 1024.0 ) * m_scale,
                            ( trackSegment.getRadius() - ((double)trackSegment.getWidthEnd()) / 1024.0 ) * m_scale );
                }
            }

            // Paint kerbs
            paintKerbs( trackSegment, g2d );

            // Paint fence
            paintFence( trackSegment, g2d );
        }
        g2d.setColor(oldColor);

        // display the computer car line
        paintCCLine( m_track.getCCLine(), g2d );

        // reset transformations
        g2d.setTransform( oldTrans );
    }

    /**
      Draw an arc with center (x,y), starting angle dStAngle, end angle dEndAngle, start radius dStRadius
      and end radius dEndRadius.
      Used to draw all curved lines.
      To be able to draw 'circles' with varying radius, a large number of short straights is drawn.
      Zooming/Panning appears outside of this method.
    */

    private void drawArc( Graphics2D g2d, int x, int y, double dStAngle, double dEndAngle,
                     double dStRadius, double dEndRadius)
    {
        double r, a, r0;
        int px, py;

        // EndAngle has to be within 2 * PI of StAngle, else a full circle
        // will be drawn.
        while ( dEndAngle - dStAngle > Math.PI * 2 )
            dEndAngle -= Math.PI * 2;

        // radius change per angle unit (radiens)
        a = (dEndRadius - dStRadius)/(dEndAngle - dStAngle);
        // calculate reference radius
        r0 = dStRadius - a * dStAngle;
        do
        {
            // calculate new radius
            r=r0+a*dStAngle;
            
            px = x + new Double( r*Math.cos(dStAngle)).intValue();
            py = y - new Double( r*Math.sin(dStAngle)).intValue();

            // Draw very short line @@@
            g2d.drawLine(px, py, px + 1, py + 1 );

            if (r > 10)
                dStAngle += 1/r;
            else if (r < -10)
                dStAngle -= 1/r;
            else
            {
                dStAngle += 0.1;
            }
        }
        while(dStAngle < dEndAngle);

        // draw a last short line to complete the arc
        px = x + new Double( r*Math.cos(dEndAngle) ).intValue();
        py = y - new Double( r*Math.sin(dEndAngle) ).intValue();
        g2d.drawLine( px, py, px + 1, py + 1 );
    }

    private Track m_track;
    private AffineTransform standardTrans;
    private double m_scale;
    private boolean m_fFirstTime;

    public void setTrack(Track track) {
        m_track = track;
        m_fFirstTime = true; // trigger calculations on first drawing
    }

    public void zoomIn() {
        m_scale = m_scale * 1.5;
        Dimension d = getSize();
        repaint(0, 0, 0, d.width, d.height );
    }

    public void zoomOut() {
        m_scale = m_scale / 1.5;
        Dimension d = getSize();
        repaint(0, 0, 0, d.width, d.height );
    }

    public void panX( int nXPan ) {
        standardTrans.translate( nXPan, 0 );
        Dimension d = getSize();
        repaint(0, 0, 0, d.width, d.height );
    }

    public void panY( int nYPan ) {
        standardTrans.translate( 0, nYPan );
        Dimension d = getSize();
        repaint(0, 0, 0, d.width, d.height );
    }

    public void moveTo(int x, int y) {
        // Set coordinate to be the point in the bottom left corner.
        // Calculate new translation matrix.
        standardTrans.setToIdentity();
        // Negative Y scale effectively changes Y direction (ascending
        // values from botton to top)
        standardTrans.scale( 1.0, -1.0 );
        standardTrans.translate( x, y);
        // repaint with new settings
        Dimension d = getSize();
        repaint(0, 0, 0, d.width, d.height );
    }

    protected void paintFence(final TrackSegment trackSegment, Graphics2D g2d) {
        boolean fLeftFence, fRightFence, fLeftFenceBridged, fRightFenceBridged;
        double dXDiffFence, dYDiffFence;
        double dXDiff, dYDiff;
        int nFenceStartX, nFenceStartY;

        // Check if fences are present
        fLeftFenceBridged = (trackSegment.getFlags() & 0x20) != 0;
        fLeftFence = !fLeftFenceBridged && ((trackSegment.getFlags() & 0x2000) == 0);
        fRightFenceBridged = (trackSegment.getFlags() & 0x10) != 0;
        fRightFence = !fRightFenceBridged && ((trackSegment.getFlags() & 0x1000) == 0);

        // calculate x/y differences from track width based on which the fence
        // distance will be calculated. @@@ different track width at start and end of segment possible!
        dXDiff = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
        dYDiff = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;

        // calculate fence distance from middle of the road.
        double dFenceDistStart, dFenceDistEnd;

        // set drawing colour for fences
        Color nonFenceColor;
        nonFenceColor = g2d.getColor();
        g2d.setColor(Color.cyan);

        if ( fLeftFence )
        {
            // Any bridged fence left for drawing?
            if ( m_fLeftFenceBridgedPrev )
            {
                // Bridging ends here
                g2d.drawLine( m_aXBridgePoints[ 0 ],
                              m_aYBridgePoints[ 0 ],
                              m_aXBridgePoints[ 1 ],
                              m_aYBridgePoints[ 1 ]);
                // clear bridge flag
                m_fLeftFenceBridgedPrev = false;
            }

            if ( trackSegment.getCurvature() == 0 )
            {
                // Straight track segment
                // Fence distance is measured in 1/32s of the track width, so to get
                // to the point where the fence is, multiply the X/YDiff by (1 + 1/32 FenceDist).
                dXDiffFence = dXDiff * ( 1.0 + ((double)m_nLeftFenceDistPrev) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)m_nLeftFenceDistPrev) / 32.0);
                nFenceStartX = new Double((trackSegment.getPosXStart() - dXDiffFence) * m_scale).intValue();
                nFenceStartY = new Double((trackSegment.getPosYStart() + dYDiffFence) * m_scale).intValue();
                dXDiffFence = dXDiff * ( 1.0 + ((double)trackSegment.getFenceDistL()) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)trackSegment.getFenceDistL()) / 32.0);;
                g2d.drawLine(nFenceStartX,
                             nFenceStartY,
                             new Double((trackSegment.getPosXEnd() - dXDiffFence) * m_scale).intValue(),
                             new Double((trackSegment.getPosYEnd() + dYDiffFence) * m_scale).intValue());
            }
            else
            {
                // curve
                dFenceDistStart = ( (double)trackSegment.getWidthStart() / 1024.0 ) * ( 1.0 + ((double)m_nLeftFenceDistPrev) / 32.0);
                dFenceDistEnd   = ( (double)trackSegment.getWidthEnd() / 1024.0 ) * ( 1.0 + ((double)trackSegment.getFenceDistL()) / 32.0);
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + dFenceDistStart ) * m_scale,
                            ( trackSegment.getRadius() + dFenceDistEnd ) * m_scale );
                }
                else
                {
                    // left turn: give start/end angle in opposite order.
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            // Note: negative radius, this add fence dist!
                            ( trackSegment.getRadius() + dFenceDistEnd ) * m_scale,
                            ( trackSegment.getRadius() + dFenceDistStart ) * m_scale );
                }
            }
        };

        if ( fRightFence )
        {
            // Any bridged fence left for drawing?
            if ( m_fRightFenceBridgedPrev )
            {
                g2d.drawLine( m_aXBridgePoints[ 2 ],
                              m_aYBridgePoints[ 2 ],
                              m_aXBridgePoints[ 3 ],
                              m_aYBridgePoints[ 3 ]);
                // clear bridge flag
                m_fRightFenceBridgedPrev = false;
            }

            if ( trackSegment.getCurvature() == 0 )
            {
                dXDiffFence = dXDiff * ( 1.0 + ((double)m_nRightFenceDistPrev) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)m_nRightFenceDistPrev) / 32.0);
                nFenceStartX = new Double((trackSegment.getPosXStart() + dXDiffFence) * m_scale).intValue();
                nFenceStartY = new Double((trackSegment.getPosYStart() - dYDiffFence) * m_scale).intValue();
                dXDiffFence = dXDiff * ( 1.0 + ((double)trackSegment.getFenceDistR()) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)trackSegment.getFenceDistR()) / 32.0);;
                g2d.drawLine(nFenceStartX,
                             nFenceStartY,
                             new Double((trackSegment.getPosXEnd() + dXDiffFence) * m_scale).intValue(),
                             new Double((trackSegment.getPosYEnd() - dYDiffFence) * m_scale).intValue());
            } // straight segment
            else
            {
                // curve
                dFenceDistStart = ( (double)trackSegment.getWidthStart() / 1024.0 ) * ( 1.0 + ((double)m_nRightFenceDistPrev) / 32.0);
                dFenceDistEnd   = ( (double)trackSegment.getWidthEnd() / 1024.0 ) * ( 1.0 + ((double)trackSegment.getFenceDistR()) / 32.0);
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - dFenceDistStart ) * m_scale,
                            ( trackSegment.getRadius() - dFenceDistEnd ) * m_scale );
                }
                else
                {
                    // left turn: give start/end angle in opposite order.
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            // Note: negative radius, thus subtract fence dist!
                            ( trackSegment.getRadius() - dFenceDistEnd ) * m_scale,
                            ( trackSegment.getRadius() - dFenceDistStart ) * m_scale );
                }
            }
        }; 
        g2d.setColor( nonFenceColor );

        // Check bridging and calculate coordinates for later drawing.
        if ( fLeftFenceBridged )
        {
            if ( !m_fLeftFenceBridgedPrev )
            {
                // calculate starting point of bridged fence and store in array
                dXDiffFence = dXDiff * ( 1.0 + ((double)m_nLeftFenceDistPrev) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)m_nLeftFenceDistPrev) / 32.0);
                m_aXBridgePoints[ 0 ] = new Double((trackSegment.getPosXStart() - dXDiffFence) * m_scale).intValue();
                m_aYBridgePoints[ 0 ] = new Double((trackSegment.getPosYStart() + dYDiffFence) * m_scale).intValue();
                // set flag that starting point was found
                m_fLeftFenceBridgedPrev = true;
            }
            // Always store end point into array. Will be overwritten when next segment
            // is also "bridged"
            dXDiffFence = dXDiff * ( 1.0 + ((double)trackSegment.getFenceDistL()) / 32.0);
            dYDiffFence = dYDiff * ( 1.0 + ((double)trackSegment.getFenceDistL()) / 32.0);;
            m_aXBridgePoints[ 1 ] = new Double((trackSegment.getPosXEnd() - dXDiffFence) * m_scale).intValue();
            m_aYBridgePoints[ 1 ] = new Double((trackSegment.getPosYEnd() + dYDiffFence) * m_scale).intValue();
        };
        if ( fRightFenceBridged )
        {
            if ( !m_fRightFenceBridgedPrev )
            {
                // calculate starting point of bridged fence and store in array
                dXDiffFence = dXDiff * ( 1.0 + ((double)m_nRightFenceDistPrev) / 32.0);
                dYDiffFence = dYDiff * ( 1.0 + ((double)m_nRightFenceDistPrev) / 32.0);
                m_aXBridgePoints[ 2 ] = new Double((trackSegment.getPosXStart() + dXDiffFence) * m_scale).intValue();
                m_aYBridgePoints[ 2 ] = new Double((trackSegment.getPosYStart() - dYDiffFence) * m_scale).intValue();
                // set flag that starting point was found
                m_fRightFenceBridgedPrev = true;
            }
            // Always store end point into array. Will be overwritten when next segment
            // is also "bridged"
            dXDiffFence = dXDiff * ( 1.0 + ((double)trackSegment.getFenceDistR()) / 32.0);
            dYDiffFence = dYDiff * ( 1.0 + ((double)trackSegment.getFenceDistR()) / 32.0);;
            m_aXBridgePoints[ 3 ] = new Double((trackSegment.getPosXEnd() + dXDiffFence) * m_scale).intValue();
            m_aYBridgePoints[ 3 ] = new Double((trackSegment.getPosYEnd() - dYDiffFence) * m_scale).intValue();
        };

        // store fence distance for next segment
        m_nLeftFenceDistPrev = trackSegment.getFenceDistL();
        m_nRightFenceDistPrev = trackSegment.getFenceDistR();
    } // paintFence

    // When kerbs are present, a green line is painted just outside the track itself.
    // Distance between track and green line is 1/4 of half track width (i.e. the
    // distance between track middle and border).
    protected void paintKerbs(final TrackSegment trackSegment, Graphics2D g2d)
    {
        // set drawing colour for kerbs
        Color colorOld;
        colorOld = g2d.getColor();
        g2d.setColor(Color.green);

        // Width unit is 1/1024 of TLU.
        double dXDiffStart = Math.cos( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
        double dYDiffStart = Math.sin( trackSegment.getAngleStart() * ANGLE_SCALE_RAD ) * trackSegment.getWidthStart() / 1024.0;
        double dXDiffEnd   = Math.cos( trackSegment.getAngleEnd()   * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;
        double dYDiffEnd   = Math.sin( trackSegment.getAngleEnd()   * ANGLE_SCALE_RAD ) * trackSegment.getWidthEnd() / 1024.0;

        if ((trackSegment.getFlags() & 0x800) != 0 )
        {
            // Left kerbs are present
            if ( trackSegment.getCurvature() == 0 )
            {
                // straight
                int aXPoints[] = new int[ 4 ];
                int aYPoints[] = new int[ 4 ];
                aXPoints[ 0 ] = new Double((trackSegment.getPosXStart() - dXDiffStart) * m_scale).intValue();
                aYPoints[ 0 ] = new Double((trackSegment.getPosYStart() + dYDiffStart) * m_scale).intValue();
                aXPoints[ 1 ] = new Double((trackSegment.getPosXStart() - ( dXDiffStart * 1.25 ) ) * m_scale).intValue();
                aYPoints[ 1 ] = new Double((trackSegment.getPosYStart() + ( dYDiffStart * 1.25 ) ) * m_scale).intValue();

                aXPoints[ 2 ] = new Double((trackSegment.getPosXEnd() - ( dXDiffEnd * 1.25 ) ) * m_scale).intValue();
                aYPoints[ 2 ] = new Double((trackSegment.getPosYEnd() + ( dXDiffEnd * 1.25 ) ) * m_scale).intValue();
                aXPoints[ 3 ] = new Double((trackSegment.getPosXEnd() - dXDiffEnd) * m_scale).intValue();
                aYPoints[ 3 ] = new Double((trackSegment.getPosYEnd() + dYDiffEnd) * m_scale).intValue();
                g2d.drawPolygon( aXPoints, aYPoints, 4 );
            }
            else
            {
                // curved segment
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    // kerbs are on outer side
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() + ( 1.25 * (((double)trackSegment.getWidthStart()) / 1024.0 ))) * m_scale,
                            ( trackSegment.getRadius() + ( 1.25 * (((double)trackSegment.getWidthEnd()) / 1024.0 ))) * m_scale );
                }
                else
                {
                    // left turn: give start/end angle in opposite order
                    // kerbs are on inner side
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            // Note: in this case, radius is negative
                            ( trackSegment.getRadius() + ( 1.25 * (((double)trackSegment.getWidthEnd()) / 1024.0 ))) * m_scale,
                            ( trackSegment.getRadius() + ( 1.25 * (((double)trackSegment.getWidthStart()) / 1024.0 ))) * m_scale );
                }
                // short straight pieces to connect to track edge.
                g2d.drawLine( new Double( ( trackSegment.getPosXStart() - dXDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYStart() + dYDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosXStart() - 1.25 * dXDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYStart() + 1.25 * dYDiffStart ) * m_scale ).intValue() );
                g2d.drawLine( new Double( ( trackSegment.getPosXEnd() - dXDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYEnd() + dYDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosXEnd() - 1.25 * dXDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYEnd() + 1.25 * dYDiffEnd) * m_scale ).intValue() );
            }
        }

        if ((trackSegment.getFlags() & 0x400) != 0 )
        {
            // Right kerbs are present
            if ( trackSegment.getCurvature() == 0 )
            {
                // straight
                // straight
                int aXPoints[] = new int[ 4 ];
                int aYPoints[] = new int[ 4 ];
                aXPoints[ 0 ] = new Double((trackSegment.getPosXStart() + dXDiffStart) * m_scale).intValue();
                aYPoints[ 0 ] = new Double((trackSegment.getPosYStart() - dYDiffStart) * m_scale).intValue();
                aXPoints[ 1 ] = new Double((trackSegment.getPosXStart() + ( dXDiffStart * 1.25 ) ) * m_scale).intValue();
                aYPoints[ 1 ] = new Double((trackSegment.getPosYStart() - ( dYDiffStart * 1.25 ) ) * m_scale).intValue();

                aXPoints[ 2 ] = new Double((trackSegment.getPosXEnd() + ( dXDiffEnd * 1.25 ) ) * m_scale).intValue();
                aYPoints[ 2 ] = new Double((trackSegment.getPosYEnd() - ( dXDiffEnd * 1.25 ) ) * m_scale).intValue();
                aXPoints[ 3 ] = new Double((trackSegment.getPosXEnd() + dXDiffEnd) * m_scale).intValue();
                aYPoints[ 3 ] = new Double((trackSegment.getPosYEnd() - dYDiffEnd) * m_scale).intValue();
                g2d.drawPolygon( aXPoints, aYPoints, 4 );
            }
            else
            {
                // curved segment
                if ( trackSegment.getCurvature() > 0 )
                {
                    // right turn
                    // kerbs are on inner side
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            ( trackSegment.getRadius() - ( 1.25 * (((double)trackSegment.getWidthStart()) / 1024.0 ))) * m_scale,
                            ( trackSegment.getRadius() - ( 1.25 * (((double)trackSegment.getWidthEnd()) / 1024.0 ))) * m_scale );
                    // short straight pieces to connect to track edge.
                    // @@@ missing
                }
                else
                {
                    // left turn: give start/end angle in opposite order
                    // kerbs are on inner side
                    drawArc(g2d,
                            new Double( trackSegment.getPosXCenter() * m_scale ).intValue(),
                            new Double( trackSegment.getPosYCenter() * m_scale ).intValue(),
                            Math.PI + trackSegment.getAngleEnd() * ANGLE_SCALE_RAD,
                            Math.PI + trackSegment.getAngleStart() * ANGLE_SCALE_RAD,
                            // Note: in this case, radius is negative
                            ( trackSegment.getRadius() - ( 1.25 * (((double)trackSegment.getWidthEnd()) / 1024.0 ))) * m_scale,
                            ( trackSegment.getRadius() - ( 1.25 * (((double)trackSegment.getWidthStart()) / 1024.0 ))) * m_scale );
                }
                // short straight pieces to connect to track edge.
                g2d.drawLine( new Double( ( trackSegment.getPosXStart() + dXDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYStart() - dYDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosXStart() + 1.25 * dXDiffStart ) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYStart() - 1.25 * dYDiffStart ) * m_scale ).intValue() );
                g2d.drawLine( new Double( ( trackSegment.getPosXEnd() + dXDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYEnd() - dYDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosXEnd() + 1.25 * dXDiffEnd) * m_scale ).intValue(),
                              new Double( ( trackSegment.getPosYEnd() - 1.25 * dYDiffEnd) * m_scale ).intValue() );
            }
        }

        // reset to old drawing color
        g2d.setColor( colorOld );
    } // paintKerbs

